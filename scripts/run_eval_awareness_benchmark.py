"""Run a local eval-awareness benchmark showcase.

The default run is deterministic and offline. To benchmark a hosted or local
OpenAI-compatible endpoint, set EVAL_AWARENESS_BASE_URL and
EVAL_AWARENESS_API_KEY, then pass --http-model MODEL_NAME.
"""

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.eval_awareness import EvalAwarenessBenchmarkSuite
from src.eval_awareness.artifacts import ArtifactWriter
from src.eval_awareness.dataset import (
    examples_to_tasks,
    examples_to_validation_set,
    load_eval_awareness_jsonl,
    starter_examples,
)
from src.eval_awareness.reporting import ReportExporter
from src.eval_awareness.runner import HTTPChatModelClient, ScriptedModelClient


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Run an eval-awareness benchmark showcase"
    )
    parser.add_argument(
        "--http-model",
        help="Model name for an OpenAI-compatible /chat/completions endpoint",
    )
    parser.add_argument(
        "--http-name", default="http-model", help="Display name for the HTTP model"
    )
    parser.add_argument(
        "--dataset",
        help="Optional JSONL dataset path using the EvalAwarenessExample schema",
    )
    parser.add_argument(
        "--n-rollouts", type=int, default=1, help="Rollouts per model/task/variant"
    )
    parser.add_argument(
        "--output-dir",
        help="Optional directory for manifest, raw JSONL, summary JSON, and Markdown report",
    )
    parser.add_argument(
        "--temperature",
        type=float,
        default=0.0,
        help="Sampling temperature when supported",
    )
    parser.add_argument(
        "--max-tokens",
        type=int,
        default=512,
        help="Maximum generated tokens when supported",
    )
    parser.add_argument(
        "--seeds", help="Comma-separated rollout seeds, when supported by the provider"
    )
    return parser


def main() -> None:
    args = build_parser().parse_args()
    models = [ScriptedModelClient()]
    if args.http_model:
        models.append(
            HTTPChatModelClient.from_env(name=args.http_name, model=args.http_model)
        )

    examples = (
        load_eval_awareness_jsonl(args.dataset) if args.dataset else starter_examples()
    )
    tasks = examples_to_tasks(examples)
    validation_set = examples_to_validation_set(examples)
    seeds = [int(seed) for seed in args.seeds.split(",")] if args.seeds else None
    report = EvalAwarenessBenchmarkSuite().run(
        models=models,
        tasks=tasks,
        validation_set=validation_set,
        n_rollouts=args.n_rollouts,
        temperature=args.temperature,
        max_tokens=args.max_tokens,
        seeds=seeds,
    )
    as_dict = report.to_dict()
    print(json.dumps(as_dict, indent=2, sort_keys=True))

    if args.output_dir:
        paths = ArtifactWriter(args.output_dir).write(
            report=report.behavior_shift,
            models=models,
            tasks=tasks,
            n_rollouts=args.n_rollouts,
            notes="Generated by scripts/run_eval_awareness_benchmark.py",
        )
        exporter = ReportExporter(args.output_dir)
        csv_path = exporter.export_model_summary_csv(report.behavior_shift)
        html_path = exporter.export_html(report.behavior_shift)
        artifact_dict = {key: str(value) for key, value in paths.__dict__.items()}
        artifact_dict["model_summary_csv"] = str(csv_path)
        artifact_dict["html_report"] = str(html_path)
        print(json.dumps({"artifacts": artifact_dict}, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
